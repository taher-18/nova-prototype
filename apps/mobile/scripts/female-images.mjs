// Builds the female exercise photo map from apps/mobile/assets/exercises/female.
// Name files <exerciseId>_0.jpg and <exerciseId>_1.jpg (start and end position),
// the same ids as the default photos, then run:  node apps/mobile/scripts/female-images.mjs
// Only use photos you have the rights to (own shoot or a licence that allows apps).
import { readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const mobile = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(mobile, 'assets', 'exercises', 'female');
const files = (await readdir(dir)).filter((f) => /_\d\.(jpe?g|png|webp)$/i.test(f)).sort();

const byId = new Map();
for (const f of files) {
  const id = f.replace(/_\d\.\w+$/i, '');
  byId.set(id, [...(byId.get(id) ?? []), f]);
}
const lines = [...byId].map(
  ([id, list]) => `  '${id}': [${list.map((f) => `require('../../../assets/exercises/female/${f}')`).join(', ')}],`,
);
await writeFile(
  join(mobile, 'src', 'features', 'exercises', 'images.female.generated.ts'),
  `// Generated by apps/mobile/scripts/female-images.mjs. Do not edit.\n/* eslint-disable */\n` +
    `export const EXERCISE_IMAGES_FEMALE: Record<string, number[]> = {\n${lines.join('\n')}${lines.length ? '\n' : ''}};\n`,
);
console.log(`${byId.size} exercises with female photos`);
