// Downloads the start/end photos for every curated exercise from
// free-exercise-db (The Unlicense, public domain) into the mobile app, so
// images work offline, and generates the static require() map Metro needs.
//
// Usage: node scripts/fetch-exercise-images.mjs [path/to/exercises.json]
// If ImageMagick (`magick` or `convert`) is installed, images are resized to
// 480px wide to keep the app small.
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DATASET_URL = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json';
const IMAGE_BASE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mobile = join(root, '..', '..', 'apps', 'mobile');
const outDir = join(mobile, 'assets', 'exercises');

function findImageMagick() {
  for (const bin of ['magick', 'convert']) {
    try {
      execFileSync(bin, ['-version'], { stdio: 'ignore' });
      return bin;
    } catch {}
  }
  return null;
}

const dataset = process.argv[2]
  ? JSON.parse(await readFile(process.argv[2], 'utf8'))
  : await (await fetch(DATASET_URL)).json();
const byId = new Map(dataset.map((e) => [e.id, e]));
const curated = JSON.parse(await readFile(join(root, 'data/curated-exercises.json'), 'utf8')).exercises;
const magick = findImageMagick();
await mkdir(outDir, { recursive: true });

const map = [];
for (const { id } of curated) {
  const images = (byId.get(id)?.images ?? []).slice(0, 2);
  const files = [];
  for (const [i, path] of images.entries()) {
    const res = await fetch(IMAGE_BASE + path);
    if (!res.ok) throw new Error(`${path}: ${res.status}`);
    const file = `${id}_${i}.jpg`;
    const target = join(outDir, file);
    await writeFile(target, Buffer.from(await res.arrayBuffer()));
    if (magick) {
      execFileSync(magick, [target, '-resize', '480x>', '-strip', '-quality', '72', target]);
    }
    files.push(file);
  }
  map.push([id, files]);
}

const lines = map.map(
  ([id, files]) => `  '${id}': [${files.map((f) => `require('../../../assets/exercises/${f}')`).join(', ')}],`,
);
await writeFile(
  join(mobile, 'src', 'features', 'exercises', 'images.generated.ts'),
  `// Generated by packages/shared/scripts/fetch-exercise-images.mjs. Do not edit.\n` +
    `// Photos: free-exercise-db (The Unlicense, public domain).\n` +
    `/* eslint-disable */\n` +
    `export const EXERCISE_IMAGES: Record<string, number[]> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`Saved ${map.reduce((n, [, f]) => n + f.length, 0)} images${magick ? ' (resized)' : ''}`);
